//! A translated crate: its items, the names they print with, and the files they go to.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::{Path, PathBuf};

use crate::print;
use crate::ts::{FieldId, Function, Item, SymId};

/// The runtime every module imports helpers from, written beside the crate root: each
/// file's path from there, and its text.
pub const RUNTIME: &[(&str, &str)] = &[
	("rt.ts", include_str!("../runtime/rt.ts")),
	("rt/iter.ts", include_str!("../runtime/rt/iter.ts")),
	("rt/task.ts", include_str!("../runtime/rt/task.ts")),
];

/// The first line of every generated file, which also marks it as safe to replace.
pub const HEADER: &str = "// Generated by rust2-ts. Do not edit.";

/// A Rust module path, from the crate root.
pub type ModPath = Vec<String>;

#[derive(Debug)]
pub struct Symbol {
	pub module: ModPath,
	/// The name it would like, before collisions are resolved.
	pub base: String,
	/// Appended, after a `$`, when the base collides; empty for a numbered suffix.
	pub suffix: String,
	/// The class a method belongs to.
	pub owner: Option<SymId>,
	pub kind: SymKind,
	/// Its source position in rustc's source map, which numbers files in the order it
	/// loads them.
	pub order: u32,
	/// The function instance it is, printed in full; empty for anything else.
	pub instance: String,
	/// The final name, set by [`Program::name`].
	pub name: String,
}

impl Symbol {
	/// Where it sorts among its module's items or its owner's methods: in source order,
	/// and the instances of one generic item by their suffix, then in full. None of it
	/// depends on the order translation reaches them in.
	pub fn key(&self) -> (u32, &str, &str, &str) {
		(self.order, &self.base, &self.suffix, &self.instance)
	}
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SymKind {
	Struct,
	/// A type alias, which has no value.
	Union,
	Function,
	/// A class's method, called on its receiver: only drop glue's `[Symbol.dispose]`.
	Method,
}

#[derive(Debug)]
pub struct FieldInfo {
	pub owner: SymId,
	pub base: String,
	pub name: String,
}

/// A Rust source file, for source maps.
#[derive(Debug)]
pub struct Source {
	pub path: PathBuf,
	pub text: String,
}

#[derive(Debug, Default)]
pub struct Program {
	pub syms: Vec<Symbol>,
	pub fields: Vec<FieldInfo>,
	/// Module-level items, by the symbol each defines.
	pub items: Vec<Item>,
	/// The methods of each class, by owner.
	pub methods: HashMap<SymId, Vec<Function>>,
	/// The structs whose values are plain objects; the others are classes.
	pub plain: HashSet<SymId>,
	pub sources: Vec<Source>,
}

impl Program {
	pub fn sym(&mut self, sym: Symbol) -> SymId {
		self.syms.push(sym);
		self.syms.len() - 1
	}

	pub fn field(&mut self, owner: SymId, base: String) -> FieldId {
		self.fields.push(FieldInfo {
			owner,
			base,
			name: String::new(),
		});
		self.fields.len() - 1
	}

	/// Put every item and method in order, and name every symbol and field, resolving
	/// collisions within each scope in that order.
	pub fn name(&mut self) {
		let syms = &self.syms;
		self.items
			.sort_by(|a, b| syms[item_sym(a)].key().cmp(&syms[item_sym(b)].key()));
		for methods in self.methods.values_mut() {
			methods.sort_by(|a, b| syms[a.sym].key().cmp(&syms[b.sym].key()));
		}

		let mut scopes: BTreeMap<Scope, Vec<SymId>> = BTreeMap::new();
		for (id, sym) in self.syms.iter().enumerate() {
			let scope = match sym.owner {
				Some(owner) => Scope::Owner(owner),
				None => Scope::Module(sym.module.clone()),
			};
			scopes.entry(scope).or_default().push(id);
		}
		for field in &self.fields {
			scopes.entry(Scope::Owner(field.owner)).or_default();
		}

		for (scope, mut ids) in scopes {
			ids.sort_by(|&a, &b| self.syms[a].key().cmp(&self.syms[b].key()));
			let mut taken = HashSet::new();
			match &scope {
				// The runtime's import binding.
				Scope::Module(_) => {
					taken.insert("rt".to_string());
				}
				// What a class already defines.
				Scope::Owner(_) => taken.extend(["constructor".to_string(), "prototype".to_string()]),
			}
			// Instances sharing a name are all told apart, so none looks like the only one.
			let mut shared: HashMap<&str, usize> = HashMap::new();
			for &id in &ids {
				*shared.entry(self.syms[id].base.as_str()).or_default() += 1;
			}
			let shared: HashSet<String> = shared
				.into_iter()
				.filter(|(_, n)| *n > 1)
				.map(|(b, _)| b.to_string())
				.collect();
			for id in ids {
				let sym = &self.syms[id];
				let base = match shared.contains(&sym.base) && !sym.suffix.is_empty() {
					true => format!("{}${}", sym.base, sym.suffix),
					false => sym.base.clone(),
				};
				let name = unique(&mut taken, &base, "");
				self.syms[id].name = name;
			}
			if let Scope::Owner(owner) = scope {
				for field in self.fields.iter_mut().filter(|f| f.owner == owner) {
					let base = match taken.contains(&field.base) {
						// A name a class already defines: the field gives way.
						true => format!("_{}", field.base),
						false => field.base.clone(),
					};
					field.name = unique(&mut taken, &base, "");
				}
			}
		}
	}

	/// Write every module, the runtime, and their source maps to `out`.
	pub fn write(&self, out: &Path) -> Result<(), String> {
		clean(out)?;
		let mut modules: BTreeMap<&ModPath, Vec<&Item>> = BTreeMap::new();
		for item in &self.items {
			modules.entry(&self.syms[item_sym(item)].module).or_default().push(item);
		}
		if modules
			.keys()
			.any(|module| module.first().is_some_and(|name| name == "rt"))
		{
			return Err("a top-level module named `rt` would replace the runtime, rt.ts and rt/".into());
		}

		for (path, text) in RUNTIME {
			write_file(&out.join(path), &format!("{HEADER}\n{text}"))?;
		}
		for (module, items) in modules {
			let path = out.join(module_file(module));
			let printed = print::module(self, module, &items, &path)?;
			write_file(&path, &printed.code)?;
			write_file(&path.with_extension("ts.map"), &printed.map)?;
		}
		Ok(())
	}
}

#[derive(PartialEq, Eq, PartialOrd, Ord)]
enum Scope {
	Module(ModPath),
	Owner(SymId),
}

fn unique(taken: &mut HashSet<String>, base: &str, suffix: &str) -> String {
	let mut name = base.to_string();
	if taken.contains(&name) && !suffix.is_empty() {
		name = format!("{base}${suffix}");
	}
	let mut n = 2;
	while taken.contains(&name) {
		name = format!("{base}${n}");
		n += 1;
	}
	taken.insert(name.clone());
	name
}

pub fn item_sym(item: &Item) -> SymId {
	match item {
		Item::Struct { sym, .. } | Item::Union { sym, .. } => *sym,
		Item::Function(f) => f.sym,
	}
}

/// The file a module is written to, relative to the output directory.
pub fn module_file(module: &[String]) -> PathBuf {
	match module {
		[] => PathBuf::from("lib.ts"),
		[parents @ .., last] => parents.iter().collect::<PathBuf>().join(format!("{last}.ts")),
	}
}

/// Remove what an earlier run generated, and nothing else.
fn clean(out: &Path) -> Result<(), String> {
	let Ok(entries) = std::fs::read_dir(out) else {
		return Ok(());
	};
	for entry in entries {
		let path = entry.map_err(|err| format!("reading {}: {err}", out.display()))?.path();
		if path.is_dir() {
			clean(&path)?;
			// Only succeeds once nothing else is left in it.
			let _ = std::fs::remove_dir(&path);
			continue;
		}
		let generated = match path.extension().and_then(|e| e.to_str()) {
			Some("ts") => std::fs::read_to_string(&path).is_ok_and(|text| text.starts_with(HEADER)),
			Some("map") => path
				.file_stem()
				.is_some_and(|stem| stem.to_string_lossy().ends_with(".ts")),
			_ => false,
		};
		if generated {
			std::fs::remove_file(&path).map_err(|err| format!("removing {}: {err}", path.display()))?;
		}
	}
	Ok(())
}

/// Write `text` to `path`, creating its directory.
pub fn write_file(path: &Path, text: &str) -> Result<(), String> {
	if let Some(dir) = path.parent() {
		std::fs::create_dir_all(dir).map_err(|err| format!("creating {}: {err}", dir.display()))?;
	}
	std::fs::write(path, text).map_err(|err| format!("writing {}: {err}", path.display()))
}
