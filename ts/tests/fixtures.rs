//! Each fixture under `fixtures/` is translated, compared with its `expected/` snapshot,
//! type-checked with `tsc`, and, if it has a harness, run against its native build.
//!
//! `UPDATE_EXPECT=1 cargo test` rewrites the snapshots.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const TARGET: &str = "wasm32-unknown-unknown";

fn manifest_dir() -> PathBuf {
	PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn scratch() -> PathBuf {
	PathBuf::from(env!("CARGO_TARGET_TMPDIR"))
}

fn cargo() -> Command {
	Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
}

fn fixture(name: &str) -> PathBuf {
	manifest_dir().join("fixtures").join(name)
}

/// Run the driver on a fixture with `config` and `args`, in its own build directory per
/// `build`.
fn driver(name: &str, config: &Path, args: &[&std::ffi::OsStr], build: &str) -> Output {
	Command::new(env!("CARGO_BIN_EXE_rust2-ts"))
		.arg("--config")
		.arg(config)
		.arg("--manifest-path")
		.arg(fixture(name).join("Cargo.toml"))
		.args(args)
		.env("CARGO_TARGET_DIR", scratch().join(build))
		.output()
		.expect("running rust2-ts")
}

/// Run the driver on a fixture, returning its output directory and what it printed.
fn translate(name: &str) -> (PathBuf, Output) {
	let out = scratch().join(name).join("out");
	let config = fixture(name).join("ts.toml");
	let output = driver(name, &config, &["--out".as_ref(), out.as_ref()], "build");
	(out, output)
}

fn translated(name: &str) -> PathBuf {
	let (out, output) = translate(name);
	assert!(
		output.status.success(),
		"translating {name} failed:\n{}",
		String::from_utf8_lossy(&output.stderr)
	);
	out
}

/// The generated TypeScript, by path relative to `dir`, without the runtime.
fn sources(dir: &Path) -> Vec<(PathBuf, String)> {
	let mut files = Vec::new();
	let mut stack = vec![dir.to_path_buf()];
	while let Some(next) = stack.pop() {
		let Ok(entries) = std::fs::read_dir(&next) else {
			continue;
		};
		for entry in entries {
			let path = entry.unwrap().path();
			if path.is_dir() {
				stack.push(path);
			} else if path.extension().is_some_and(|e| e == "ts") {
				let rel = path.strip_prefix(dir).unwrap().to_path_buf();
				let text = std::fs::read_to_string(&path).unwrap();
				// A hand-written caller copied in beside the output is no part of it.
				if rel != Path::new("rt.ts") && !rel.starts_with("rt") && text.starts_with("// Generated by rust2-ts.")
				{
					files.push((rel, text));
				}
			}
		}
	}
	files.sort();
	files
}

/// Compare the output with the fixture's `expected/` directory.
fn snapshot(name: &str, out: &Path) {
	let expected = fixture(name).join("expected");
	let got = sources(out);
	if std::env::var_os("UPDATE_EXPECT").is_some() {
		let _ = std::fs::remove_dir_all(&expected);
		for (rel, text) in &got {
			let path = expected.join(rel);
			std::fs::create_dir_all(path.parent().unwrap()).unwrap();
			std::fs::write(path, text).unwrap();
		}
		return;
	}
	let want = sources(&expected);
	let names = |files: &[(PathBuf, String)]| files.iter().map(|(p, _)| p.clone()).collect::<Vec<_>>();
	assert_eq!(
		names(&got),
		names(&want),
		"{name}: the generated files differ; rerun with UPDATE_EXPECT=1"
	);
	for ((rel, got), (_, want)) in got.iter().zip(&want) {
		assert!(
			got == want,
			"{name}: {} differs from its snapshot; rerun with UPDATE_EXPECT=1\n{}",
			rel.display(),
			diff(want, got)
		);
	}
}

/// The first lines where two texts differ.
fn diff(want: &str, got: &str) -> String {
	let (want, got): (Vec<&str>, Vec<&str>) = (want.lines().collect(), got.lines().collect());
	let start = want.iter().zip(&got).take_while(|(a, b)| a == b).count();
	let mut out = String::new();
	for line in want.iter().skip(start).take(8) {
		out.push_str(&format!("- {line}\n"));
	}
	for line in got.iter().skip(start).take(8) {
		out.push_str(&format!("+ {line}\n"));
	}
	out
}

/// Type-check the output as strict, erasable TypeScript, which Node runs as is.
fn typecheck(out: &Path) {
	// The runtime's settings: strict, and erasable so Node runs it as is.
	let runtime = manifest_dir().join("runtime").join("tsconfig.json");
	let config = format!(
		"{{ \"extends\": {:?}, \"files\": [], \"include\": [\"**/*.ts\"] }}\n",
		runtime.display().to_string()
	);
	std::fs::write(out.join("tsconfig.json"), config).unwrap();
	let output = Command::new("tsc")
		.arg("-p")
		.arg(out)
		.output()
		.expect("running tsc, which the dev shell provides");
	assert!(
		output.status.success(),
		"tsc rejected the output:\n{}",
		String::from_utf8_lossy(&output.stdout)
	);
}

/// Run the harness natively, as wasm32, and translated, on the same inputs: the
/// translated side through `entry`, a module in `out`. `extra` are `differential.ts`'s
/// arguments after the case count.
fn differential(package: &str, out: &Path, entry: &str, cases: u32, extra: &[&str]) {
	let target_dir = scratch().join("wasm");
	let status = cargo()
		.args([
			"build",
			"--locked",
			"--package",
			package,
			"--target",
			TARGET,
			"--target-dir",
		])
		.arg(&target_dir)
		.arg("--manifest-path")
		.arg(manifest_dir().join("Cargo.toml"))
		.status()
		.expect("running cargo");
	assert!(status.success(), "building {package} for {TARGET} failed");
	let wasm = target_dir
		.join(TARGET)
		.join("debug")
		.join(format!("{}.wasm", package.replace('-', "_")));
	std::fs::write(out.join("package.json"), "{ \"type\": \"module\" }\n").unwrap();
	let output = Command::new("node")
		.arg(manifest_dir().join("tests").join("differential.ts"))
		.arg(&wasm)
		.arg(out.join(entry))
		.arg(cases.to_string())
		.args(extra)
		.output()
		.expect("running node, which the dev shell provides");
	let stdout = String::from_utf8_lossy(&output.stdout);
	let stderr = String::from_utf8_lossy(&output.stderr);
	assert!(
		output.status.success(),
		"{package} differs from native Rust:\n{stdout}{stderr}"
	);
	println!("{stdout}");
}

#[test]
fn codec() {
	let out = translated("codec");
	snapshot("codec", &out);
	typecheck(&out);
	differential("codec-fixture", &out, "harness.ts", 20_000, &[]);
}

/// Adding a root changes only the output of what it reaches: everything else keeps its
/// text and order, though translation reaches it in another order.
#[test]
fn source_order() {
	let config = std::fs::read_to_string(fixture("codec").join("ts.toml")).unwrap();
	let roots = r#"roots = ["harness::run", "bench::run"]"#;
	assert!(config.contains(roots), "codec's roots changed: update this test");
	let dir = scratch().join("codec").join("order");
	std::fs::create_dir_all(&dir).unwrap();
	let run = |name: &str, with: &str| {
		let path = dir.join(format!("{name}.toml"));
		std::fs::write(&path, config.replace(roots, with)).unwrap();
		let out = dir.join(name);
		let output = driver("codec", &path, &["--out".as_ref(), out.as_ref()], "order");
		assert!(
			output.status.success(),
			"translating codec with {with} failed:\n{}",
			String::from_utf8_lossy(&output.stderr)
		);
		sources(&out)
	};
	let base = run("base", r#"roots = ["harness::run"]"#);
	// First, so that translation reaches what both share in another order.
	let added = run("added", r#"roots = ["bench::run", "harness::run"]"#);
	for (rel, text) in &base {
		let more = added.iter().find(|(r, _)| r == rel).map(|(_, text)| text);
		let more = more.unwrap_or_else(|| panic!("{} is gone once bench::run is added", rel.display()));
		let mut rest = lines(more).into_iter();
		for line in lines(text) {
			assert!(
				rest.any(|l| l == line),
				"{}: this line changed or moved once bench::run was added:\n{line}",
				rel.display()
			);
		}
	}
}

/// A file's lines, with a line per imported name, so that importing one more name
/// changes no other line.
fn lines(text: &str) -> Vec<String> {
	let mut lines = Vec::new();
	for line in text.lines() {
		match line.strip_prefix("import { ").and_then(|l| l.split_once(" } from ")) {
			Some((names, from)) => {
				lines.extend(names.split(", ").map(|name| format!("import {{ {name} }} from {from}")))
			}
			None => lines.push(line.to_string()),
		}
	}
	lines
}

#[test]
fn lang() {
	let out = translated("lang");
	snapshot("lang", &out);
	// Hand-written callers, type-checked against the output they call: one runs it, and
	// one mixes integer types, which `tsc` must refuse.
	for file in ["caller.ts", "brands.ts"] {
		std::fs::copy(manifest_dir().join("fixtures/lang").join(file), out.join(file)).unwrap();
	}
	typecheck(&out);
	differential("lang-fixture", &out, "caller.ts", 50_000, &["wide"]);
}

/// Futures and drops: the harness is hand-written TS around the translation, whose FIFO
/// executor logs every poll, wake, and drop as the fixture's native one does.
#[test]
fn task() {
	let out = translated("task");
	snapshot("task", &out);
	let harness = manifest_dir().join("tests").join("task.ts").display().to_string();
	let text = format!(
		r#"import * as rt from "./rt.ts";
import {{ Log }} from "./log.ts";
import {{ Channel, Guard, blocks, drain, sum }} from "./model.ts";
import {{ harness }} from {harness:?};

export {{ cases }} from {harness:?};
export const run = harness({{ Pending: rt.Pending, u64: rt.u64, Log, Channel, Guard, sum, drain, blocks }});
"#
	);
	std::fs::write(out.join("caller.ts"), text).unwrap();
	typecheck(&out);
	differential("task-fixture", &out, "caller.ts", 20_000, &[]);
}

/// Each construct outside the subset fails with its span, and nothing is written.
#[test]
fn reject() {
	let (out, output) = translate("reject");
	assert!(!output.status.success(), "translating reject succeeded");
	assert!(!out.join("lib.ts").exists(), "a failed translation wrote output");
	let stderr = String::from_utf8_lossy(&output.stderr);
	// Each error and where it points, without rustc's rendering of the source.
	let mut got = String::new();
	let mut lines = stderr.lines().peekable();
	while let Some(line) = lines.next() {
		if let Some(error) = line.strip_prefix("error: rust2-ts: ") {
			got.push_str(error);
			if let Some(at) = lines.peek().and_then(|l| l.trim_start().strip_prefix("--> ")) {
				got.push_str(&format!(" at {at}"));
			}
			got.push('\n');
		}
	}
	let path = fixture("reject").join("expected.txt");
	if std::env::var_os("UPDATE_EXPECT").is_some() {
		std::fs::write(&path, &got).unwrap();
		return;
	}
	let want = std::fs::read_to_string(&path).unwrap_or_default();
	assert!(
		got == want,
		"the errors differ; rerun with UPDATE_EXPECT=1\n{}",
		diff(&want, &got)
	);
}

/// A census ranks every refusal in the crate, reached from each of its items, and
/// succeeds where translation fails.
#[test]
fn census() {
	let census = scratch().join("reject").join("census.md");
	let config = fixture("reject").join("ts.toml");
	let output = driver("reject", &config, &["--census".as_ref(), census.as_ref()], "census");
	assert!(
		output.status.success(),
		"the census of reject failed:\n{}",
		String::from_utf8_lossy(&output.stderr)
	);
	let got = std::fs::read_to_string(&census).unwrap();
	let path = fixture("reject").join("census.md");
	if std::env::var_os("UPDATE_EXPECT").is_some() {
		std::fs::write(&path, &got).unwrap();
		return;
	}
	let want = std::fs::read_to_string(&path).unwrap_or_default();
	assert!(
		got == want,
		"the census differs; rerun with UPDATE_EXPECT=1\n{}",
		diff(&want, &got)
	);
}
